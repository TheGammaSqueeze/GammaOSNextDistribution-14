const char* tr(StringId id) {
    if (id < 0 || id >= STR_COUNT) return "";
    const char* s = kStrings[id][sCurrentLocale];
    if (!s || !s[0]) s = kStrings[id][LOCALE_EN];
    return s ? s : "";
}

NanoLocale nanoGetLocale() { return sCurrentLocale; }

void nanoSetLocale(NanoLocale locale) {
    if (locale >= 0 && locale < LOCALE_COUNT) {
        sCurrentLocale = locale;
    }
}

const LocaleInfo& nanoGetLocaleInfo(NanoLocale locale) {
    return kLocaleInfo[locale];
}

void nanoInitLocaleFromSystem() {
    char locale[PROPERTY_VALUE_MAX] = {};
    property_get("persist.sys.locale", locale, "en-US");

    // Extract language code (before the dash)
    char lang[8] = {};
    const char* dash = strchr(locale, '-');
    if (dash) {
        size_t len = dash - locale;
        if (len >= sizeof(lang)) len = sizeof(lang) - 1;
        memcpy(lang, locale, len);
        lang[len] = '\0';
    } else {
        strncpy(lang, locale, sizeof(lang) - 1);
    }

    // Extract region (after the dash)
    char region[8] = {};
    if (dash && dash[1]) {
        strncpy(region, dash + 1, sizeof(region) - 1);
    }

    for (int i = 0; i < LOCALE_COUNT; i++) {
        if (strcmp(lang, kLocaleInfo[i].code) == 0) {
            // For Chinese, distinguish CN vs TW by region
            if (strcmp(lang, "zh") == 0) {
                if (strcmp(region, "TW") == 0 || strcmp(region, "HK") == 0) {
                    sCurrentLocale = LOCALE_ZH_TW;
                } else {
                    sCurrentLocale = LOCALE_ZH_CN;
                }
            } else {
                sCurrentLocale = (NanoLocale)i;
            }
            ALOGI("NanoMenu: locale set to %s (%s)",
                  kLocaleInfo[sCurrentLocale].code,
                  kLocaleInfo[sCurrentLocale].englishName);
            return;
        }
    }
    sCurrentLocale = LOCALE_EN;
    ALOGI("NanoMenu: locale defaulting to English (system=%s)", locale);
}

void nanoApplyLocaleToSystem() {
    const LocaleInfo& info = kLocaleInfo[sCurrentLocale];
    char locale[32];
    snprintf(locale, sizeof(locale), "%s-%s", info.code, info.regionCode);
    char cmd[128];
    snprintf(cmd, sizeof(cmd), "setprop persist.sys.locale %s", locale);
    system(cmd);
    ALOGI("NanoMenu: applied system locale %s", locale);
}

