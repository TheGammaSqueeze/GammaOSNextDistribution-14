#!/usr/bin/env python3
"""Writes NanoCtrThemeBuiltin.inc: the HOME Menu's built-in colour themes (Red, Blue, Yellow,
Pink, Black) from the web replica's theme/<Name>.json bodies, as ThemeBody initialisers for
NanoCtrTheme.cpp.

usage: ctr_themes.py <romfs dir> <output .inc>
"""
import json
import os
import sys

NAMES = ["Red", "Blue", "Yellow", "Pink", "Black"]   # ThemeEntry type 1 index 0..4
BLOCKS = ["cursor", "folder", "file", "arrowButton", "arrow", "openButton", "closeButton", "gameText",
          "bottomSolid", "bottomOuter", "folderBackground", "folderArrow", "bottomCornerButton",
          "topCornerButton", "demoText"]


def block(b):
    if not b:
        return "{}"
    fields = []
    alpha = -1
    for k, v in b.items():
        if isinstance(v, list):
            fields.append('{"%s", {%d, %d, %d}}' % (k, v[0], v[1], v[2]))
        elif isinstance(v, int) and k == "alpha":
            alpha = v
    return "{true, {%s}, %d}" % (", ".join(fields), alpha)


def main():
    romfs, out = sys.argv[1], sys.argv[2]
    lines = ["// Generated by tools/ctr_themes.py from the web replica's theme/*.json. Do not edit.", ""]
    for name in NAMES:
        with open(os.path.join(romfs, "theme", name + ".json")) as f:
            d = json.load(f)
        top = d["top"]
        c = top.get("color")
        if c:
            top_s = '{"%s", true, {%d, %d, %d}, %d, %d, %d, %d}' % (
                top["drawType"], c["color"][0], c["color"][1], c["color"][2], c["gradient"], c["opacity"],
                c.get("unknown05", 100), c.get("unknown06", 100))
        else:
            top_s = '{"%s"}' % top["drawType"]
        blocks = ",\n        ".join(block(d["colors"].get(k)) for k in BLOCKS)
        lines.append('makeBody("%s", %s, "%s", %s, {{\n        %s}}),' % (
            name, top_s, d["bottom"]["drawType"], "true" if d.get("bgmEnabled") else "false", blocks))
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
