# Generate NanoOskKana.h: the romaji -> hiragana mapping table for the Nano OSK
# Japanese input method. This is the standard, finite "wapuro romaji" table
# (gojuon + youon + dakuten/handakuten). The runtime KanaInput engine layers
# the sokuon (small tsu from doubled consonants) and syllabic-n rules on top of
# this table, so only the direct syllable map lives here.
#
# Kanji conversion is intentionally NOT handled: there is no Japanese morphology
# dictionary in the tree, so the Nano IME produces hiragana (which is valid
# Japanese text). Kana->kanji is future work that needs a vendored dictionary.
#
# Usage:
#   python3 tools/osk/gen_osk_kana.py \
#       --out frameworks/base/cmds/gammaos-nano/NanoOskKana.h

