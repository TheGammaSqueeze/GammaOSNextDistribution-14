def c_string(s):
    out = '"'
    for b in s.encode("utf-8"):
        if 0x20 <= b <= 0x7E and b not in (0x22, 0x5C):
            out += chr(b)
        elif b == 0x22:
            out += '\\"'
        elif b == 0x5C:
            out += "\\\\"
        else:
            out += "\\x%02x" % b
    return out + '"'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    rows = sorted(KANA.items())   # sorted by romaji for binary search
    out = []
    out.append("// AUTO-GENERATED by tools/osk/gen_osk_kana.py. DO NOT EDIT.")
    out.append("// Romaji -> hiragana table for the Nano Japanese input method.")
    out.append("")
    out.append("#ifndef GAMMAOS_NANO_OSK_KANA_H")
    out.append("#define GAMMAOS_NANO_OSK_KANA_H")
    out.append("")
    out.append("namespace android {")
    out.append("")
    out.append("// One romaji spelling and the hiragana it produces. Sorted by")
    out.append("// `romaji` so the engine can binary-search and test prefixes.")
    out.append("struct OskKana { const char* romaji; const char* kana; };")
    out.append("static const OskKana kOskKana[] = {")
    for r, k in rows:
        out.append("    { %-8s, %-12s }," % (c_string(r), c_string(k)))
    out.append("};")
    out.append("static const int kOskKanaCount = %d;" % len(rows))
    out.append("")
    out.append("} // namespace android")
    out.append("")
    out.append("#endif // GAMMAOS_NANO_OSK_KANA_H")
    out.append("")
    with open(args.out, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print("Generated %s (%d romaji entries)" % (args.out, len(rows)))


if __name__ == "__main__":
    main()
